async(page)=>{
  const results=[];const expect=(name,pass,detail)=>{if(!pass)throw new Error(name+': '+JSON.stringify(detail));results.push({name,passed:true});};
  await page.setViewportSize({width:1440,height:900});
  await page.evaluate(()=>{const w=window.__macOS.wm;[...w.windows.value].forEach(a=>w.closeWindow(a.id));window.__macOS.systemStore.setAppearance('light');w.openApp('settings');});
  const settings=page.getByRole('region',{name:'系统设置',exact:true});await settings.getByRole('button',{name:'深色',exact:true}).click();
  expect('Dark appearance applies',await page.evaluate(()=>document.documentElement.classList.contains('dark')));
  await settings.getByRole('button',{name:'跟随系统',exact:true}).click();
  expect('System appearance follows media preference',await page.evaluate(()=>window.__macOS.systemStore.appearance==='system'&&window.__macOS.systemStore.isDark===matchMedia('(prefers-color-scheme: dark)').matches));
  await settings.getByRole('button',{name:'紫',exact:true}).click();
  expect('Accent is applied and persisted',await page.evaluate(()=>getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()==='#9454c9'&&JSON.parse(localStorage.getItem('sub2-desktop-preferences')).accentColor==='purple'));
  await settings.getByRole('button',{name:'强调色底',exact:true}).click();
  expect('Dock icon appearance is applied',await page.locator('nav .mac-app-icon--tinted').count()>0);
  await settings.getByRole('button',{name:'浅色',exact:true}).click();
  await settings.getByRole('button',{name:'原色',exact:true}).click();
  await settings.getByRole('button',{name:'系统蓝',exact:true}).click();
  await page.getByRole('button',{name:'控制中心',exact:true}).click();
  const controls=page.getByRole('region',{name:'控制中心',exact:true});await controls.waitFor();
  await controls.getByRole('slider',{name:'界面音量'}).fill('0');
  expect('UI sound is muted',await page.evaluate(()=>window.__macOS.systemStore.volume===0));
  await controls.getByRole('slider',{name:'桌面亮度'}).fill('65');
  expect('Desktop brightness affects real overlay',await page.evaluate(()=>Number(document.querySelector('.desktop-dimmer').style.opacity)>0));
  await controls.getByRole('slider',{name:'桌面亮度'}).fill('100');
  await controls.getByRole('button',{name:/桌面小组件/}).click();
  expect('Widgets can be hidden',await page.getByRole('complementary',{name:'桌面概览'}).count()===0);
  await controls.getByRole('button',{name:/桌面小组件/}).click();
  await page.keyboard.press('Escape');await controls.waitFor({state:'detached'});
  expect('Escape closes Control Center',await controls.count()===0);
  const before=await settings.boundingBox();const title=settings.locator('.mac-window-titlebar');const rect=await title.boundingBox();
  await page.mouse.move(rect.x+180,rect.y+22);await page.mouse.down();await page.mouse.move(rect.x+110,rect.y+45,{steps:8});await page.mouse.up();
  const after=await settings.boundingBox();expect('Window drag moves without losing content',Math.abs(after.x-before.x)>40&&after.y>=34,{before,after});
  await title.dblclick({position:{x:180,y:22}});expect('Titlebar double click maximizes',await settings.getAttribute('data-window-state')==='maximized');
  await title.dblclick({position:{x:180,y:22}});expect('Titlebar double click restores',await settings.getAttribute('data-window-state')==='normal');
  await page.setViewportSize({width:390,height:844});await settings.getByRole('button',{name:'设置分类',exact:true}).click();
  await settings.getByRole('button',{name:'桌面与壁纸',exact:true}).click();
  await settings.getByRole('button',{name:'macOS Sequoia',exact:true}).click();
  expect('Mobile settings navigation and wallpaper work',await page.evaluate(()=>window.__macOS.systemStore.wallpaper==='sequoia'));
  await page.screenshot({path:'output/playwright/polish/settings-wallpaper-mobile.png',animations:'disabled'});
  await page.evaluate(()=>window.__macOS.systemStore.setWallpaper('tahoe'));
  await page.setViewportSize({width:1440,height:900});
  await page.evaluate(()=>{const w=window.__macOS.wm;[...w.windows.value].forEach(a=>w.closeWindow(a.id));});
  await page.getByRole('navigation',{name:'管理员桌面应用'}).getByRole('button',{name:'账号管理',exact:true}).dblclick();
  await page.getByRole('region',{name:'账号管理',exact:true}).waitFor();
  expect('Desktop icon double click opens app',await page.getByRole('region',{name:'账号管理',exact:true}).count()===1);
  return {passed:true,results,fixtureOnly:true};
}
